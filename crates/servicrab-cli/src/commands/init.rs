//! `servicrab init [--path PATH] [--force]` — create an example config file.

use std::path::Path;

/// Template written by `servicrab init`.
const EXAMPLE_TOML: &str = r#"# servicrab.toml — generated by `servicrab init`
#
# Edit this file to describe the processes that make up your local stack.
# Run `servicrab check` to validate it and `servicrab list` to see the
# services.

version = 1

[project]
name = "my-project"

# ── Project-level environment variables ───────────────────────────────────────
# These are merged into every service's environment (service env takes
# precedence over project env, which takes precedence over the inherited shell
# environment).
# [project.env]
# RUST_LOG = "info"

# ── Services ──────────────────────────────────────────────────────────────────
# Each [services.<name>] block defines one managed process.
#
# Required fields:
#   command       List of executable + arguments, e.g. ["node", "server.js"]
#
# Optional fields:
#   cwd           Working directory (default: config file's directory)
#   env           Per-service environment variables
#   depends_on    Services that must start before this one, e.g. ["db"]
#   autostart     Whether to start automatically (default: true)
#   restart       never | on-failure | always  (default: never)
#   restart_delay         Minimum backoff before first restart (default: 1s)
#   restart_max_delay     Maximum backoff cap (default: 30s)
#   max_restarts          Give up after this many attempts (default: 10)
#   stable_after          Consider stable after running this long (default: 60s)
#   shutdown_signal       term | int | quit | hup  (default: term)
#   shutdown_timeout      Wait this long before forcibly killing (default: 10s)

[services.api]
command = ["echo", "Replace me with your API server command"]
cwd = "."
restart = "on-failure"
restart_delay = "1s"
restart_max_delay = "30s"
max_restarts = 5
depends_on = ["db"]

[services.api.env]
PORT = "3000"

[services.db]
command = ["echo", "Replace me with your database command"]
restart = "always"

[services.worker]
command = ["echo", "Replace me with your worker command"]
restart = "never"
autostart = false

[services.worker.env]
DATABASE_URL = "postgres://localhost/mydb"
"#;

/// Run the `init` subcommand.
pub fn run(path: &Path, force: bool) -> Result<(), String> {
    if path.exists() && !force {
        return Err(format!(
            "{} already exists. Use --force to overwrite, or edit it manually.",
            path.display()
        ));
    }

    std::fs::write(path, EXAMPLE_TOML)
        .map_err(|e| format!("could not write {}: {e}", path.display()))?;

    println!(
        "Created {}. Edit it, then run `servicrab check`.",
        path.display()
    );
    Ok(())
}
